"""Run every pair against every available matcher and write results/BENCHMARK.md.

All numbers in that file come from this script. Re-run it and they change with
the machine; nothing is transcribed by hand.

    python scripts/benchmark.py
"""
from __future__ import annotations

import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "backend"))

from seleno import matchers, pipeline, store  # noqa: E402

OUT = os.path.join(ROOT, "results")


def fmt(v, d=3):
    if v is None:
        return "--"
    try:
        return ("%." + str(d) + "f") % float(v)
    except (TypeError, ValueError):
        return str(v)


def main():
    os.makedirs(OUT, exist_ok=True)
    st = store.Store(os.path.join(ROOT, "data"))
    avail = [k for k, v in matchers.MATCHERS.items() if v["available"]]
    unavail = [(k, v.get("reason", "")) for k, v in matchers.MATCHERS.items() if not v["available"]]

    lines = [
        "# Benchmark",
        "",
        "Generated by `scripts/benchmark.py` on %s." % time.strftime("%Y-%m-%d %H:%M:%S"),
        "Every figure is produced by an actual pipeline run. Nothing is hand-entered.",
        "",
        "Read `ASSUMPTIONS.md` before quoting any of this. In particular: reprojection",
        "RMSE measures self-consistency, not accuracy; the ground-truth columns are the",
        "accuracy figures, and they exist only for pairs where the true transform is",
        "known by construction.",
        "",
    ]
    if unavail:
        lines += ["**Matchers not available in this environment:** "
                  + ", ".join("`%s` (%s)" % (k, r) for k, r in unavail), ""]

    raw = {}

    # ------------------------------------------------------------------ 1
    lines += ["## 1. Seleno pipeline, default settings, every pair", "",
              "| Pair | Matcher | Model | Cand. | Inliers | Inlier ratio | Retained "
              "| Reproj RMSE (px) | GT corner err (px) | GT corner err (m) | Coverage "
              "| NCC before → after | Runtime (s) | Verdict |",
              "|---|---|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|---|"]
    for p in st.pairs:
        opts = pipeline.Options()
        opts.model_type = p.get("recommended_model", "homography")
        src, ref = st.images(p["id"])
        res = pipeline.run(p, src, ref, opts)
        res.pop("_images")
        raw[p["id"] + "/default"] = res
        m = res["metrics"]
        gt = m.get("ground_truth") or {}
        lines.append("| `%s` | %s | %s | %d | %d | %.1f%% | %d | %s | %s | %s | %.0f%% | %s → %s | %.2f | %s |" % (
            p["id"], opts.matcher, opts.model_type, m["candidate_matches"], m["inliers"],
            100 * m["inlier_ratio"], m["selected_matches"],
            fmt(m["reprojection"].get("rmse_px")), fmt(gt.get("corner_error_px")),
            fmt(gt.get("corner_error_m")), 100 * m["spatial_coverage"],
            fmt(m.get("ncc_before"), 2), fmt(m.get("ncc_after"), 2),
            m["runtime_total_s"], "accepted" if res["verdict"]["registered"] else "REJECTED"))
    lines.append("")

    # ------------------------------------------------------------------ 2
    lines += ["## 2. Matcher comparison", "",
              "Same pipeline, same settings, only the matcher changes.", ""]
    for p in st.pairs:
        lines += ["### `%s` — %s" % (p["id"], p["name"]), "",
                  "| Matcher | Cand. | Inliers | Inlier ratio | Reproj RMSE (px) "
                  "| GT corner err (px) | Coverage | Runtime (s) | Verdict |",
                  "|---|--:|--:|--:|--:|--:|--:|--:|---|"]
        src, ref = st.images(p["id"])
        for mk in avail:
            opts = pipeline.Options()
            opts.matcher = mk
            opts.model_type = p.get("recommended_model", "homography")
            res = pipeline.run(p, src, ref, opts)
            res.pop("_images")
            raw["%s/%s" % (p["id"], mk)] = res
            m = res["metrics"]
            gt = m.get("ground_truth") or {}
            if res.get("error"):
                lines.append("| `%s` | — | — | — | — | — | — | — | error: %s |"
                             % (mk, res["error"]))
                continue
            lines.append("| `%s` | %d | %d | %.1f%% | %s | %s | %.0f%% | %.2f | %s |" % (
                mk, m["candidate_matches"], m["inliers"], 100 * m["inlier_ratio"],
                fmt(m["reprojection"].get("rmse_px")), fmt(gt.get("corner_error_px")),
                100 * m["spatial_coverage"], m["runtime_total_s"],
                "accepted" if res["verdict"]["registered"] else "REJECTED"))
        lines.append("")

    # ------------------------------------------------------------------ 3
    lines += ["## 3. Ablation — what each stage is worth", "",
              "`naive` is what a pipeline looks like with the ratio test loosened to 0.95,",
              "no mutual-consistency check, no preprocessing and no spatial selection.",
              "The remaining rows disable one stage at a time from the full pipeline.", ""]
    ablations = [
        ("full pipeline", {}),
        ("naive (no preprocessing, ratio 0.95, no mutual check, no spatial selection)",
         dict(preprocess_enabled=False, ratio=0.95, mutual_check=False, spatial_enabled=False)),
        ("no preprocessing", dict(preprocess_enabled=False)),
        ("no mutual-consistency check", dict(mutual_check=False)),
        ("no spatial selection (top-K by confidence)", dict(spatial_enabled=False)),
        ("no geometric verification", dict(verify_enabled=False)),
        ("no GSD harmonisation", dict(harmonise_gsd=False)),
    ]
    for p in st.pairs:
        lines += ["### `%s`" % p["id"], "",
                  "| Configuration | Cand. | Inliers | Inlier ratio | Reproj RMSE (px) "
                  "| GT corner err (px) | Coverage | Verdict |",
                  "|---|--:|--:|--:|--:|--:|--:|---|"]
        src, ref = st.images(p["id"])
        for label, over in ablations:
            opts = pipeline.Options()
            opts.model_type = p.get("recommended_model", "homography")
            for k, v in over.items():
                setattr(opts, k, v)
            res = pipeline.run(p, src, ref, opts)
            res.pop("_images")
            raw["%s/ablate:%s" % (p["id"], label)] = res
            m = res["metrics"]
            gt = m.get("ground_truth") or {}
            lines.append("| %s | %d | %d | %.1f%% | %s | %s | %.0f%% | %s |" % (
                label, m["candidate_matches"], m["inliers"], 100 * m["inlier_ratio"],
                fmt(m["reprojection"].get("rmse_px")), fmt(gt.get("corner_error_px")),
                100 * m["spatial_coverage"],
                "accepted" if res["verdict"]["registered"] else "REJECTED"))
        lines.append("")

    with open(os.path.join(OUT, "BENCHMARK.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    with open(os.path.join(OUT, "benchmark_raw.json"), "w", encoding="utf-8") as fh:
        json.dump(raw, fh, indent=2)
    print("wrote %s" % os.path.join(OUT, "BENCHMARK.md"))


if __name__ == "__main__":
    main()
